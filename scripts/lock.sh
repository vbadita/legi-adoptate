#!/usr/bin/env bash
# Regenerate the lock files from *.in in throwaway venvs (exactly what pip resolves).
set -euo pipefail
cd "$(dirname "$0")/../collector"
for name in requirements requirements-dev; do
  tmp=$(mktemp -d)
  python3.12 -m venv "$tmp"
  "$tmp/bin/pip" install -q --disable-pip-version-check -r "$name.in" -c constraints.txt
  "$tmp/bin/pip" check
  { echo "# Generated by scripts/lock.sh from $name.in. Do not edit."
    "$tmp/bin/pip" freeze --all --exclude pip; } > "$name.txt"
  rm -rf "$tmp"
done
