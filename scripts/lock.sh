#!/usr/bin/env bash
# Regenerate collector/requirements-dev.txt in a throwaway venv (exactly what pip resolves).
set -euo pipefail
cd "$(dirname "$0")/../collector"
tmp=$(mktemp -d)
python3.12 -m venv "$tmp"
"$tmp/bin/pip" install -q --disable-pip-version-check -r requirements-dev.in -c constraints.txt
"$tmp/bin/pip" check
{ echo "# Generated by scripts/lock.sh from requirements-dev.in. Do not edit."
  "$tmp/bin/pip" freeze --all --exclude pip; } > requirements-dev.txt
rm -rf "$tmp"
